create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  device_id text not null,
  plot_id text,
  moisture numeric(6, 2) not null check (moisture >= 0 and moisture <= 100),
  recorded_at timestamptz not null default now()
);

create index if not exists sensor_readings_recorded_at_idx
  on public.sensor_readings (recorded_at desc);

create index if not exists sensor_readings_plot_recorded_at_idx
  on public.sensor_readings (plot_id, recorded_at desc);

alter table public.sensor_readings enable row level security;

grant select, insert on public.sensor_readings to service_role;
grant usage, select on sequence public.sensor_readings_id_seq to service_role;
