export default function ReadAloudLabel({
  children,
  text,
  color = '#166534',
  textStyle,
  containerStyle,
}) {
  const spokenText = ISAN_DESCRIPTIONS[text] || text;

  const speak = () => {
    Speech.stop().catch((error) => console.error('Could not stop previous speech:', error));
    Speech.speak(spokenText, {
      language: 'th-TH',
      rate: 0.9,
      volume: 1,
      onError: (error) => console.error('Reading field description failed:', error),
    });
  };

  return (
    <View style={[styles.row, containerStyle]}>
      <Text style={[styles.label, textStyle]}>{children}</Text>
      <TouchableOpacity
        accessibilityRole="button"
        accessibilityLabel={`ฟังคำอธิบาย: ${spokenText}`}
        accessibilityHint="แตะเพื่อฟังคำอธิบายหัวข้อนี้"
        onPress={speak}
        style={[styles.button, { borderColor: color }]}
        hitSlop={4}
      >
        <Text style={[styles.icon, { color }]} accessibilityElementsHidden>
          🔊
        </Text>
      </TouchableOpacity>
    </View>
  );
}

const styles = StyleSheet.create({
  row: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: 4,
  },
  label: {
    flexShrink: 1,
  },
  button: {
    width: 30,
    height: 30,
    borderRadius: 15,
    borderWidth: 1,
    backgroundColor: '#f0fdf4',
    alignItems: 'center',
    justifyContent: 'center',
  },
  icon: {
    fontSize: 14,
  },
});
